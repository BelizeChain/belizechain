//! Benchmarking for `pallet-zk-attestation`.
//!
//! `submit_attestation` cannot synthesise its own proof. The runtime build of
//! `belizechain-zk-attestation` deliberately omits the `prover` feature, so circuit
//! synthesis and the Poseidon parameters are not linked into the chain, and there is
//! nothing here that can produce a proof. The constants below are therefore a real
//! Groth16 proof over a real Poseidon tree, generated once with the prover enabled
//! and embedded verbatim.
//!
//! Embedding a *placeholder* would have been worse than not benchmarking at all:
//! `submit_attestation` would fail the pairing on every run, so the measured weight
//! would describe the rejection path while production pays for a verification.
//!
//! The fixture is checked by `the_benchmark_fixture_is_a_valid_proof` in `tests.rs`,
//! which asserts the key and proof pass a real verification against these public
//! inputs and that every input is a canonical field element. It deliberately does
//! not compare against a freshly generated proof: `setup_for_testing` draws from
//! `thread_rng`, so a regenerated proof is valid but never byte-identical.
//!
//! Measured 2026-10-27 (steps=50, repeat=20, AC power, `BENCH_MUL=1.25`):
//! `submit_attestation` costs 22.6 ms `ref_time`, against the 10 ms the previous
//! hand-derived constant charged — the estimate under-charged by 2.3×, which is the
//! direction that lets a block be overfilled.

