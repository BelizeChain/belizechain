const FIXTURE_CIRCUIT_VERSION: u16 = 1;
const FIXTURE_SET_ID: u32 = 1;

#[benchmarks]
mod benchmarks {
    use super::*;

    /// The origin that satisfies `T::RegistryAuthority`.
    ///
    /// Benchmarks must exercise the same origin check production does, so this asks
    /// the configured `EnsureOrigin` rather than hard-coding root — a pallet whose
    /// authority is a council would otherwise be benchmarked on an origin it rejects.
    fn authority_origin<T: Config>() -> Result<T::RuntimeOrigin, &'static str> {
        T::RegistryAuthority::try_successful_origin()
            .map_err(|_| "RegistryAuthority has no successful origin")
    }

    fn bounded_key<T: Config>() -> Result<BoundedVec<u8, T::MaxVerifyingKeyLen>, &'static str> {
        BoundedVec::try_from(FIXTURE_VERIFYING_KEY.to_vec())
            .map_err(|_| "the fixture verifying key exceeds MaxVerifyingKeyLen")
    }

    /// Publish the fixture key and root so `submit_attestation` can succeed.
    fn seed_registry<T: Config>() -> Result<(), &'static str> {
        VerifyingKeys::<T>::insert(FIXTURE_CIRCUIT_VERSION, bounded_key::<T>()?);
        RegistryRoots::<T>::insert(
            FIXTURE_SET_ID,
            RegistryRoot {
                root: FIXTURE_PUBLIC_INPUTS[0],
                circuit_version: FIXTURE_CIRCUIT_VERSION,
                leaf_count: 2,
                published_at: frame_system::Pallet::<T>::block_number(),
            },
        );
        Ok(())
    }

    #[benchmark]
    fn set_registry_root() -> Result<(), BenchmarkError> {
        let origin = authority_origin::<T>()?;
        let root = FIXTURE_PUBLIC_INPUTS[0];
        // Worst case is a replace, not a first insert: the storage entry written is
        // already present, so the write pays for the larger of the two paths.
        seed_registry::<T>()?;

        #[extrinsic_call]
        _(origin, FIXTURE_SET_ID, root, FIXTURE_CIRCUIT_VERSION, 2u32);

        assert!(RegistryRoots::<T>::contains_key(FIXTURE_SET_ID));
        Ok(())
    }

    #[benchmark]
    fn set_verifying_key() -> Result<(), BenchmarkError> {
        let origin = authority_origin::<T>()?;
        let key: Vec<u8> = FIXTURE_VERIFYING_KEY.to_vec();

        #[extrinsic_call]
        _(origin, FIXTURE_CIRCUIT_VERSION, key);

        assert!(VerifyingKeys::<T>::contains_key(FIXTURE_CIRCUIT_VERSION));
        Ok(())
    }

    #[benchmark]
    fn submit_attestation() -> Result<(), BenchmarkError> {
        seed_registry::<T>()?;
        let caller: T::AccountId = whitelisted_caller();
        let proof: Vec<u8> = FIXTURE_PROOF.to_vec();
        let inputs: Vec<[u8; 32]> = FIXTURE_PUBLIC_INPUTS.to_vec();

        #[extrinsic_call]
        _(RawOrigin::Signed(caller.clone()), FIXTURE_SET_ID, proof, inputs);

        assert!(UsedNullifiers::<T>::contains_key(
            FIXTURE_SET_ID,
            &FIXTURE_PUBLIC_INPUTS[2],
        ));
        Ok(())
    }

    impl_benchmark_test_suite!(
        Pallet,
        crate::mock::new_test_ext(),
        crate::mock::Test
    );
}
