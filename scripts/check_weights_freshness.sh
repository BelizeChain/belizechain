#!/usr/bin/env bash
# ==============================================================================
# Weight freshness guard
# ==============================================================================
# Fails if any pallet's `src/weights.rs` was generated BEFORE the last change to
# that pallet's `src/lib.rs` or `src/benchmarking.rs`.
#
# Why this exists
# ---------------
# FRAME weights are generated from benchmarks. If a pallet's logic changes after
# its weights were generated, the committed weights describe storage access the
# code no longer performs - they under-count reads/writes and under-charge the
# extrinsic, which is the UNSAFE direction (a cheap extrinsic can be abused).
#
# This is not hypothetical. It has been missed twice:
#   * spec 115 shipped a stale `submit_storage_proof` (weights predated the
#     storage-commitment work).
#   * spec 116 found five more: `economy::update_inflation` (3/5 -> 4/6),
#     `landledger::register_property` (4/6 -> 4/7),
#     `landledger::transfer_property` (7/8 -> 7/10),
#     `mesh::submit_mesh_transaction` (6/4 -> 7/5) and
#     `governance::veto_emergency` (270/69 -> 271/69).
#
# The date heuristic is exact enough for its purpose: a `lib.rs` change does not
# always move a benchmarked path, so this can occasionally ask for a regeneration
# that turns out to be a no-op. That is the intended trade - a cheap false alarm
# beats silently under-charging an extrinsic.
#
# REQUIRES FULL GIT HISTORY. Under a shallow clone (`actions/checkout` defaults to
# fetch-depth: 1) `git log` reports the tip commit for every path, and this check
# becomes vacuous - it would pass on a stale tree. CI must clone with
# `fetch-depth: 0`. The script detects a shallow clone and fails loudly rather
# than reporting a false pass.
# ==============================================================================

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if [[ -f "$(git rev-parse --git-dir)/shallow" ]]; then
    echo "❌ shallow clone detected - this check needs full history." >&2
    echo "   In CI, set 'fetch-depth: 0' on actions/checkout." >&2
    exit 1
fi

FAIL=0
CHECKED=0

for weights in pallets/*/src/weights.rs; do
    [[ -f "$weights" ]] || continue
    pallet_dir="$(basename "$(dirname "$(dirname "$weights")")")"

    generated="$(grep -m1 -oE 'DATE: [0-9]{4}-[0-9]{2}-[0-9]{2}' "$weights" | cut -d' ' -f2)"
    if [[ -z "$generated" ]]; then
        echo "::error file=${weights}::no 'DATE:' header - weights must be generated by scripts/bench_weights.sh"
        FAIL=1
        continue
    fi

    # Most recent commit touching this pallet's source (lib.rs or benchmarking.rs).
    source_date="$(git log -1 --format=%cs -- \
        "pallets/${pallet_dir}/src/lib.rs" \
        "pallets/${pallet_dir}/src/benchmarking.rs" 2>/dev/null || true)"

    CHECKED=$((CHECKED + 1))
    if [[ -z "$source_date" ]]; then
        echo "   ? ${pallet_dir}: no source history found, skipped"
        continue
    fi

    if [[ "$source_date" > "$generated" ]]; then
        echo "::error file=${weights}::weights generated ${generated}, but pallet source changed ${source_date} - regenerate with scripts/bench_weights.sh"
        FAIL=1
    fi
done

echo "Checked ${CHECKED} weight file(s) against their pallet source."
if [[ "$FAIL" -ne 0 ]]; then
    echo "" >&2
    echo "❌ Stale weights. A change to lib.rs/benchmarking.rs after the weights were" >&2
    echo "   generated means the weights under-count storage access. Regenerate:" >&2
    echo "" >&2
    echo "     cargo build --release -p belizechain-node --features runtime-benchmarks" >&2
    echo "     ./scripts/bench_weights.sh --all        # must be ON AC POWER" >&2
    echo "" >&2
    exit 1
fi

echo "✅ All weight files are at least as new as their pallet source."
